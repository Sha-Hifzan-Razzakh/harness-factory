"""Perturbation generator (TSK-04): variants of a base task, by type, from a declarative spec.

A spec per base task, `catalog/perturbations/<base>.yaml`, lists the variants and their parameters. `hfx perturb`
(re)materialises one folder per variant, `catalog/tasks/<base>--<type>-<n>/`, deterministically: `task.yaml`, a
copy of the base's `reference.py` (or the spec's override), and, when the type changes the seed, the changed seed
under `seed/`. The folders are generated, never hand-edited; `hfx perturb --check` fails when they drift from the
specs (CI). A variant is an ordinary task: its own id and hash, `base_id` set, the base's split (a HELD_OUT base
gives HELD_OUT variants) and version, the base's tags plus `perturbation` and `pert:<type>`, and a
`perturbation: {type, params}` block that is part of its hash.

Types (what the variant changes; the base's oracle is kept, so the real task is graded the same way):

  tool_failure          params.faults: fault rules (kinds error, timeout, rate_limit, empty) bound to every run of
                        the variant as part of its environment (`Task.bound_faults`). Tagged `needs-retry`: a model
                        that never retries can't recover, so the replay gates leave these out (`--exclude-tag`) and
                        the scripted `retry` model solves them in the fault gate
  slow_tool             params.faults: `latency` rules, each delay below the tool's timeout_s (else it is a failure)
  injected_instruction  params.target (a seed file, a SQL statement, or a biz record field) gets params.text, an
                        instruction to do something out of scope; params.guard is a critical zero-weight check that
                        the injected action was not performed, added to the oracle
  oversized_output      params.target (a seed file) is padded with params.pad lines (a template) so that the
                        reference's params.call returns more than the inline cap (`hfx reference` checks it); the
                        answer stays reachable (the spill pages, or a narrower call)
  ambiguous_wording     params.instruction replaces the instruction: params.vague says which specifier was blurred
                        and params.why why the data still settles it (clarification is #76)

Every variant needs params.why. `memory_poisoning` (MEM-06) is reserved: its materialiser would write
`env_seed.memory_seed`, and it is refused until memory stores exist (#78).

Campaign faults: a variant that binds faults (tool_failure, slow_tool) runs clean only. `plan` leaves out its
faulted runs and `provision` refuses a fault profile on it, so its R isn't measured against itself. Its runs are
scored runs of the variant task; robustness per perturbation type is variant against base outcome, reported by
`hfx report` (section 3c), never a cell's R.
"""

from __future__ import annotations

import copy
import hashlib
import json
import os
import re
import shutil
